p='core/strings/src/main/res/values/settings.xml'
s=open(p,encoding='utf-8').read()
def repl(m):
    name=m.group(1)
    if name in M:
        return '<string name="%s">%s</string>'%(name,M[name].replace('&','&amp;').replace('<','&lt;'))
    return m.group(0)
s2=re.sub(r'<string name="([^"]+)">(.*?)</string>',repl,s,flags=re.S)
n=sum(1 for k in M if '<string name="%s">'%k in s)
open(p,'w',encoding='utf-8').write(s2)
print('translated mappings applied:',n)
